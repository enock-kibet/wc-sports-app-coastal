@freezed
abstract class DirectionDetailsInfo with _$DirectionDetailsInfo {
  const factory DirectionDetailsInfo({
    @JsonKey(name: "distance_value") int? distanceValue,
    @JsonKey(name: "duration_value") int? durationValue,
    @JsonKey(name: "e_points") String? ePoints,
    @JsonKey(name: "distance_text") String? distanceText,
    @JsonKey(name: "duration_text") String? durationText,
  }) = _DirectionDetailsInfo;

  factory DirectionDetailsInfo.fromJson(Map<String, dynamic> json) =>
      _$DirectionDetailsInfoFromJson(json);
}
